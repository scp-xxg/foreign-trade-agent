import assert from 'node:assert/strict';
import { acquisitionMessage, ACQUISITION_SKILLS } from '../src/utils/acquisitionMode';
import { useComposerStore, readComposer } from '../src/stores/composerStore';
const store = useComposerStore.getState();
store.activate('chat:a');
readComposer('chat:a').patch({ acquisitionMode: true, input: '寻找德国买家' });
const snapshot = readComposer('chat:a');
const queued = acquisitionMessage(snapshot.input, snapshot.acquisitionMode);
for (const skill of ACQUISITION_SKILLS) assert.ok(queued.includes(skill));
snapshot.consume(snapshot);
assert.equal(readComposer('chat:a').acquisitionMode, true);
store.activate('chat:b');
assert.equal(readComposer('chat:b').acquisitionMode, false);
readComposer('chat:a').patch({ acquisitionMode: false });
assert.ok(queued.includes('[获客模式：六技能工作流]'));
assert.equal(acquisitionMessage('普通消息', false), '普通消息');
assert.equal(acquisitionMessage('/compact', true), '/compact');
assert.equal(acquisitionMessage('', true), '');
store.resetForUser('another-user');
assert.equal(readComposer('chat:a').acquisitionMode, false);
console.log('Acquisition mode: skill composition, consumption, isolation and reset passed');

store.activate('chat:followup');
readComposer('chat:followup').patch({diligenceMode:true,input:'背调目标企业'});
const followupSnapshot=readComposer('chat:followup');
const {tradeWorkflowMessage,DILIGENCE_SKILLS}=await import('../src/utils/acquisitionMode');
const captured=tradeWorkflowMessage(followupSnapshot.input,followupSnapshot.acquisitionMode,followupSnapshot.diligenceMode);
for(const skill of DILIGENCE_SKILLS)assert.ok(captured.includes(skill));
assert.ok(!captured.includes('trade-customer-profile'));
assert.equal(tradeWorkflowMessage('/compact',false,true),'/compact');
assert.equal(tradeWorkflowMessage('',false,true),'');
followupSnapshot.consume(followupSnapshot);
assert.equal(readComposer('chat:followup').diligenceMode,true);
readComposer('chat:followup').patch({diligenceMode:false});
assert.ok(captured.includes('[客户背调：四技能工作流]'));
store.activate('chat:separate');assert.equal(readComposer('chat:separate').diligenceMode,false);
store.transfer('chat:followup','chat:moved');assert.equal(readComposer('chat:moved').diligenceMode,false);
readComposer('chat:moved').patch({diligenceMode:true});
store.resetForUser('followup-other-user');assert.equal(readComposer('chat:moved').diligenceMode,false);
console.log('Diligence composition, captured queue, consumption and account isolation passed');

