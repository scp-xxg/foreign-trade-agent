import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseMaterialReceipt,extractMaterialChecks,markedSegments} from '../src/utils/materialCheckReceipt';
import type {ToolCall} from '../src/types';
const fixture=JSON.parse(readFileSync('scripts/fixtures/material-check-receipt.json','utf8'));
const record=parseMaterialReceipt(fixture);assert.ok(record);
const field=record.fields[0];const segments=markedSegments(field,record.sensitive!.hits);
assert.equal(segments.map(s=>s.text).join(''),field.text);
assert.ok(segments.some(s=>s.text==='CE certified' && s.hits.length));
const tool={name:'trade_material_check',status:'success',output:JSON.stringify({ok:true,data:fixture,errors:[]})} as ToolCall;
assert.equal(extractMaterialChecks([tool]).length,1);
assert.equal(extractMaterialChecks([{...tool,status:'error'} as ToolCall]).length,0);
assert.equal(extractMaterialChecks([{...tool,name:'other'}]).length,0);
assert.equal(extractMaterialChecks([{...tool,outputTruncated:true,outputLoaded:false}]).length,0);
const bad=structuredClone(fixture);bad.sensitive.hits[0].span=[0,999999];assert.equal(parseMaterialReceipt(bad),null);
const wrong=structuredClone(fixture);wrong.sensitive.hits[0].match='wrong';assert.equal(parseMaterialReceipt(wrong),null);
assert.equal(parseMaterialReceipt({...fixture,release_authorized:true}),null);
assert.equal(extractMaterialChecks([{...tool,output:JSON.stringify({ok:false,data:fixture})}]).length,0);
console.log('Material receipt validation, failed/truncated tool guards and Unicode highlighting passed');
